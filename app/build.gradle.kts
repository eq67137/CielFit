// Release signing material lives outside the source tree (keystore.properties is
// gitignored). Absent on a fresh clone or CI, the release config is simply not
// registered, so `assembleDebug` still works for anyone without the key.
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}

android {
    namespace = "com.cielfit.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.cielfit.app"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        resourceConfigurations += listOf("en")

        // USDA FoodData Central key. The shared DEMO_KEY is heavily rate-limited
        // (30 req/hour per IP) and would make dish lookups fail for a real user,
        // so the key is injected at build time from keystore.properties or the
        // environment. Empty means the USDA tier is skipped and the bundled
        // FNRI table + estimate path still answer - the app degrades, it does
        // not break.
        val usdaKey = keystoreProps.getProperty("usdaApiKey")
            ?: System.getenv("USDA_API_KEY")
            ?: ""
        buildConfigField("String", "USDA_API_KEY", "\"$usdaKey\"")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
                enableV1Signing = true
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystoreProps.isNotEmpty()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
        freeCompilerArgs += "-opt-in=androidx.compose.material3.ExperimentalMaterial3Api"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    composeOptions {
        kotlinCompilerExtensionVersion = "1.5.14"
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
    lint {
        // A release build fails on a real error, not on style advice.
        abortOnError = true
        checkReleaseBuilds = true
    }
}

